//
// 方針：
//  - 掲載してよいのは公式サイトで確認した値（確認日つき）と、口コミが掲載されている第三者サイトの
//    所在（サイト名・URL・確認日）のみ。口コミ本文の転載・架空の口コミ・体験談の創作はしない。
//  - 凍結セクション（data/reviewTrends.ts・companies.ts の pros/cons）はここでは扱わない。
//  - ASP の計測リンク（px.a8.net 等）はここに書かない（出典リンクは各サイトの通常URLのみ）。

export interface ReviewSourceLink {
  site: string; // サイト名
  url: string; // 口コミが掲載されているページ（ASP計測リンクではない通常URL）
  note: string; // 確認できた掲載状況（件数・評価など。確認日つき）
}

export interface CompanyLead {
  metaTitle: string;
  metaDescription: string;
  h1?: string; // 指定時は H1 に使う（例：「◯◯の口コミ・評判」）
  leadHeading: string; // 冒頭の即答ボックスの見出し
  leadBody: string[]; // 冒頭の即答（公式確認値ベース）
  checkedAt: string; // 冒頭の即答・出典一覧の確認日
  sources?: ReviewSourceLink[]; // 口コミ・評判の出典一覧
  sourcesCheckedAt?: string; // 出典一覧の確認日（冒頭の即答と確認日が異なる場合のみ指定）
  faqs?: { question: string; answer: string }[];
  auditFacts?: string[]; // 「審査について」に出す公式確認済みの事実（汎用文の置き換え）
  flow?: { step: number; title: string; description: string; duration?: string }[]; // 公式の利用の流れ
  officialLinks?: { label: string; url: string }[]; // 冒頭の即答の出典（公式・公的情報の通常URL。ASP計測リンクは不可）
  related?: { href: string; label: string }[]; // 冒頭から案内する関連ページ（内部リンク）
  leadTable?: { head: [string, string]; rows: [string, string][] }; // 冒頭の即答の下に出す早見表（公式確認値のみ）
  keepCompanyAmount?: boolean; // true のとき買取可能額は companies.ts の表示のまま（feeIndex に切り替えない。サイト内の値の扱いが判断待ちの会社用）
  auditTable?: { heading: string; head: [string, string, string]; rows: [string, string, string][]; note?: string; source: string }; // 「審査について」に出す審査の流れ・必要書類・所要時間の表（公式確認値のみ）
}

