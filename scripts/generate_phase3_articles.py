    body.append(f"**ステータス:** 下書き\n")
    body.append("---\n")
    body.append(article["intro"] + "\n")
    body.append("---\n")
    for heading, content in article["sections"]:
        body.append(f"## {heading}\n")
        body.append(content + "\n")
    body.append("---\n")
    body.append("## よくある質問\n")
    for q, a in article["faqs"]:
        body.append(f"**Q: {q}**")
        body.append(f"A: {a}\n")
    body.append("---\n")
    body.append("## 関連記事\n")
    for label, href in article["related"]:
        body.append(f"- [{label}]({href})")
    body.append("")

    out = OUT_DIR / f"article-factoring-{slug}.md"
    out.write_text("\n".join(body), encoding="utf-8")
    return out


